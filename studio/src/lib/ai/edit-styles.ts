/**
 * Built-in edit style presets for Auto Edit. Each preset is concrete enough to
 * drive both Claude (as rules) and the no-AI basic editor (as parameters).
 * Users can add their own styles learned from reference videos (EditStyle table).
 */
import { z } from "zod";
import { TransitionType } from "../project/schema";

export const StyleProfile = z.object({
  name: z.string(),
  description: z.string(),
  avgShotSec: z.number().min(0.3).max(15),
  cutOnBeat: z.boolean().default(false),
  transitions: z.array(TransitionType).default([]),
  zoom: z.enum(["none", "punch-in", "slow-push", "mixed"]).default("none"),
  grade: z
    .object({
      brightness: z.number(),
      contrast: z.number(),
      saturation: z.number(),
      temperature: z.number(),
      tint: z.number(),
      vignette: z.number(),
      grain: z.number(),
    })
    .partial()
    .default({}),
  letterbox: z.number().min(0).max(0.25).default(0),
  overlays: z.array(z.enum(["film-grain", "light-leak", "light-streaks", "particles", "glitch", "scanlines"])).default([]),
  captions: z.enum(["none", "bold", "clean", "karaoke"]).default("none"),
  textStyle: z
    .object({ headlineFont: z.string(), bodyFont: z.string(), color: z.string(), accent: z.string(), uppercase: z.boolean() })
    .partial()
    .default({}),
  removeSilences: z.boolean().default(true),
  structure: z.string().default(""),
  notes: z.string().default(""),
});
export type StyleProfile = z.infer<typeof StyleProfile>;

